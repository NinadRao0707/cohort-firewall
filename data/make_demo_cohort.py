"""Generate a STAND-IN breast cancer cohort shaped like a flattened Synthea export.

Purpose: lets the team build and test the firewall before Synthea is set up.
For the demo, replace this with real Synthea output via data/flatten_synthea.py.
All values are random. No real patients are involved.

Usage: python data/make_demo_cohort.py  ->  data/demo/breast_cohort.csv + .dictionary.json
"""
import json
from pathlib import Path

import numpy as np
import pandas as pd

OUT = Path(__file__).resolve().parent / "demo"
RNG = np.random.default_rng(20261114)
N = 2400


def generate(n=N, rng=RNG) -> pd.DataFrame:
    stage_num = rng.choice([1, 2, 3, 4], n, p=[0.38, 0.34, 0.20, 0.08])
    er = rng.random(n) < 0.75
    pr = np.where(er, rng.random(n) < 0.8, rng.random(n) < 0.1)
    her2 = rng.random(n) < 0.18
    size = np.clip(rng.gamma(2.2, 10, n) + 6 * (stage_num - 1), 2, 120).round(0)
    nodes = np.clip(rng.poisson(0.4 + 1.6 * (stage_num - 1)), 0, 30)
    age = np.clip(rng.normal(61, 12, n), 25, 95).round(0)

    # follow-up, then death (ends follow-up)
    fu = np.clip(rng.normal(48, 18, n), 3, 96)
    p_death = 1 / (1 + np.exp(-(-3.4 + 0.75 * (stage_num - 1) + 0.03 * (age - 61))))
    t_death = rng.uniform(1, 96, n)
    died = (rng.random(n) < p_death) & (t_death <= fu)
    fu = np.where(died, t_death, fu).round(1)

    # 2-year recurrence, with censoring when follow-up is too short to know
    logit = (-2.3 + 0.55 * (stage_num - 1) + 0.12 * nodes + 0.008 * (size - 20)
             - 0.45 * er + 0.35 * her2 + rng.normal(0, 0.6, n))
    rec = rng.random(n) < 1 / (1 + np.exp(-logit))
    t_rec = rng.uniform(1, 24, n)
    rec2 = np.where(rec & (t_rec <= fu), 1.0, np.where(fu >= 24, 0.0, np.nan))

    race = rng.choice(["white", "black", "asian", "other"], n, p=[0.58, 0.17, 0.12, 0.13])
    eth = rng.choice(["nonhispanic", "hispanic"], n, p=[0.86, 0.14])
    notes = rng.choice(["routine follow-up", "imaging scheduled", "no new concerns", ""], n)

    return pd.DataFrame({
        "patient_id": [f"P{i:06d}" for i in range(n)],
        "cancer_type": "breast",
        "diagnosis_year": rng.integers(2012, 2021, n),
        "age_at_diagnosis": age.astype(int),
        "sex": rng.choice(["F", "M"], n, p=[0.99, 0.01]),
        "race": race, "ethnicity": eth,
        "stage": pd.Series(stage_num).map({1: "I", 2: "II", 3: "III", 4: "IV"}),
        "er_status": np.where(er, "positive", "negative"),
        "pr_status": np.where(pr, "positive", "negative"),
        "her2_status": np.where(her2, "positive", "negative"),
        "tumor_size_mm": size.astype(int),
        "nodes_positive": nodes,
        "surgery": (rng.random(n) < 0.9).astype(int),
        "chemotherapy": (rng.random(n) < 0.45 + 0.1 * (stage_num - 1)).astype(int),
        "follow_up_months": fu,
        "recurrence_2yr": rec2,
        "death_event": died.astype(int),
        "notes": notes,
    })


def dictionary() -> dict:
    c = lambda t, r, timing, d: {"type": t, "role": r, "timing": timing, "description": d}
    return {
        "dataset": {
            "name": "demo_breast_cohort",
            "source": "Cohort Firewall stand-in generator (Synthea-shaped, random values)",
            "provenance": "Generated by data/make_demo_cohort.py with a fixed seed; no real patients.",
            "license": "CC0-1.0",
            "patient_derived": False,
            "identifiable": False,
            "access": "open",
        },
        "columns": {
            "patient_id": c("id", "id", "baseline", "Pseudonymous synthetic identifier"),
            "cancer_type": c("categorical", "feature", "baseline", "Primary cancer site"),
            "diagnosis_year": c("numeric", "feature", "baseline", "Year of diagnosis (index event)"),
            "age_at_diagnosis": {**c("numeric", "demographic", "baseline", "Age in years at diagnosis"), "valid_range": [18, 105]},
            "sex": c("categorical", "demographic", "baseline", "Recorded sex"),
            "race": c("categorical", "demographic", "baseline", "Recorded race category"),
            "ethnicity": c("categorical", "demographic", "baseline", "Recorded ethnicity"),
            "stage": c("categorical", "feature", "baseline", "AJCC-style stage group at diagnosis"),
            "er_status": c("categorical", "feature", "baseline", "Estrogen receptor status"),
            "pr_status": c("categorical", "feature", "baseline", "Progesterone receptor status"),
            "her2_status": c("categorical", "feature", "baseline", "HER2 status"),
            "tumor_size_mm": {**c("numeric", "feature", "baseline", "Tumor size at diagnosis (mm)"), "valid_range": [0, 250]},
            "nodes_positive": {**c("numeric", "feature", "baseline", "Positive lymph nodes at diagnosis"), "valid_range": [0, 60]},
            "surgery": c("binary", "feature", "post_index", "Surgery received after diagnosis"),
            "chemotherapy": c("binary", "feature", "post_index", "Chemotherapy received after diagnosis"),
            "follow_up_months": c("numeric", "time", "outcome", "Months from diagnosis to last contact or death"),
            "recurrence_2yr": c("binary", "outcome", "outcome", "Recurrence within 24 months (blank if unknown)"),
            "death_event": c("binary", "outcome", "outcome", "Death observed during follow-up"),
            "notes": c("text", "text", "post_index", "Free-text administrative note"),
        },
    }


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    df = generate()
    df.to_csv(OUT / "breast_cohort.csv", index=False)
    (OUT / "breast_cohort.dictionary.json").write_text(json.dumps(dictionary(), indent=2))
    print(f"wrote {len(df)} rows to {OUT}")
